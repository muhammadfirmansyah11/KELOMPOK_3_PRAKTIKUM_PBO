    private void kirimButtonActionPerformed(java.awt.event.ActionEvent evt) {                                            
        // TODO add your handling code here:
        
        String nama = namaField.getText().trim();
        String nim = nimField.getText().trim();
        String prodi = (String) prodiComboBox.getSelectedItem();
        String jenisKelamin = "";
        
        if (priaRadioButton.isSelected()) {
            jenisKelamin = "Laki-laki";
        } else if (wanitaRadioButton.isSelected()) {
            jenisKelamin = "Perempuan";
        }
        boolean isActive = statusCheckBox.isSelected();
        
        if (nama.isEmpty() || nim.isEmpty() || jenisKelamin.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Nama, NIM, dan Jenis Kelamin wajib diisi!", 
                "Input Error", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Long.parseLong(nim);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
                    "NIM harus berupa angka!", 
                    "Input Error", 
       JOptionPane.ERROR_MESSAGE);
        return;
        }
        
        for (Mahasiswa mhs : Mahasiswa.mahasiswas) {
            if (mhs.getNim().equals(nim)) {
                JOptionPane.showMessageDialog(this,
                    "Data dengan NIM " + nim + " sudah ada!",
                "Data Duplikat",
            JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        Mahasiswa mahasiswa = new Mahasiswa(nama, nim, prodi, jenisKelamin, isActive);
        Mahasiswa.mahasiswas.add(mahasiswa);

        JOptionPane.showMessageDialog(this, 
            "Sukses menambahkan data Mahasiswa: " + nama, 
            "Sukses", 
            JOptionPane.INFORMATION_MESSAGE);

        clearForm();
        
    }                                           


